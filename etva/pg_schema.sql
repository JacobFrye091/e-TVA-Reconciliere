ALTER TABLE clients            ALTER COLUMN firm_id SET DEFAULT current_setting('app.firm_id', true)::int;
ALTER TABLE client_assignments ALTER COLUMN firm_id SET DEFAULT current_setting('app.firm_id', true)::int;
ALTER TABLE reconciliations    ALTER COLUMN firm_id SET DEFAULT current_setting('app.firm_id', true)::int;
