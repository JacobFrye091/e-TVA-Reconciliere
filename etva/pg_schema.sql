-- ===== tabele per-firma (in SQLite: fisiere SQLCipher separate; aici RLS) =====
-- firm_id are DEFAULT current_setting('app.firm_id')::int ca INSERT-urile
-- existente din etva/* (care nu cunosc coloana) sa primeasca automat firma
-- sesiunii curente si sa treaca de WITH CHECK.

CREATE TABLE IF NOT EXISTS clients(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id integer NOT NULL REFERENCES firms(id)
    DEFAULT current_setting('app.firm_id', true)::int,
  cui text NOT NULL,
  name text NOT NULL,
  gdpr_confirmat boolean NOT NULL DEFAULT FALSE,
  gdpr_confirmat_de text,
  gdpr_confirmat_la timestamptz);
-- Bazele create inainte de coloanele GDPR se aduc la zi aici (no-op pe
-- bazele deja corecte); clientii existenti raman 'neconfirmat' - starea
-- lor reala, nu una inventata.
ALTER TABLE clients ADD COLUMN IF NOT EXISTS gdpr_confirmat boolean NOT NULL DEFAULT FALSE;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS gdpr_confirmat_de text;
ALTER TABLE clients ADD COLUMN IF NOT EXISTS gdpr_confirmat_la timestamptz;
-- In SQLite UNIQUE(cui) era per-fisier, deci per-firma; pe tabela partajata
-- echivalentul corect e unicitatea pe (firm_id, cui) - doua firme de
-- contabilitate pot avea acelasi client.
ALTER TABLE clients DROP CONSTRAINT IF EXISTS clients_cui_key;
CREATE UNIQUE INDEX IF NOT EXISTS idx_clients_firm_cui ON clients(firm_id, cui);

