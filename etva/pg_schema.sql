-- Schema canonica PostgreSQL pentru e-TVA Reconciliere (etva_testare / etva_productie).
-- IDEMPOTENT: se poate aplica oricand, pe o baza goala sau pe una existenta -
--   psql -d etva_testare -f etva/pg_schema.sql
-- Corespondentul PG al portal/db.py::_SCHEMA + etva/db.py::_SCHEMA, cu trei
-- diferente structurale deliberate (vezi planning/migrare-postgres.md):
--   1. Cele 7 tabele "per-firma" (in SQLite: cate un fisier SQLCipher separat
--      per firma) devin tabele partajate cu o coloana firm_id, izolate prin
--      Row-Level Security: politica `izolare_firma` filtreaza dupa
--      current_setting('app.firm_id') pe care adaptorul o seteaza per sesiune.
--   2. Coloanele boolean/timestamp/numeric folosesc tipurile reale PG
--      (etva/pg.py::EXPECTED_SCHEMA le verifica la pornire).
--   3. firm_keys NU are foreign key spre firms - randurile orfane sunt
--      pastrate intentionat la stergerea firmelor (cheia ramane recuperabila).
-- Verificarea de conformitate: etva/pg.py::verify_schema().

-- ============ tabele portal (partajate, fara RLS - master vede tot) ============

CREATE TABLE IF NOT EXISTS firms(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  cui text UNIQUE NOT NULL,
  tip text NOT NULL DEFAULT 'contabilitate',
  active boolean NOT NULL DEFAULT TRUE,
  email_verificat boolean NOT NULL DEFAULT FALSE,
  email_verificare_token text,
  creat_la timestamptz,
  trial_expira_la timestamptz,
  ciclu_facturare text,
  trial_reminder_ultim_prag integer,
  arhivata_la timestamptz,
  reconcilieri_lunare_estimate integer);
-- Bazele create inainte de coloana de mai sus se aduc la zi aici (no-op pe
-- bazele deja corecte) - acelasi pattern ca la contracts.
ALTER TABLE firms ADD COLUMN IF NOT EXISTS reconcilieri_lunare_estimate integer;

CREATE TABLE IF NOT EXISTS users(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text UNIQUE NOT NULL,
  pw_hash text NOT NULL,
  email text,
  is_master boolean NOT NULL DEFAULT FALSE,
  onboarding_completat boolean NOT NULL DEFAULT FALSE,
  active boolean NOT NULL DEFAULT TRUE);

CREATE TABLE IF NOT EXISTS user_firms(
  user_id integer NOT NULL REFERENCES users(id),
  firm_id integer NOT NULL REFERENCES firms(id),
  role text NOT NULL,
  active boolean NOT NULL DEFAULT TRUE,
  PRIMARY KEY (user_id, firm_id));

CREATE TABLE IF NOT EXISTS firm_keys(
  firm_id integer PRIMARY KEY,
  wrapped_key bytea NOT NULL);
-- Fara FK spre firms, nici in SQLite: randurile orfane sunt politica
-- deliberata (cheia ramane recuperabila dupa stergerea administrativa a
-- firmei), iar datele reale contin deja astfel de orfani.
ALTER TABLE firm_keys DROP CONSTRAINT IF EXISTS firm_keys_firm_id_fkey;

