ALTER TABLE differences        ALTER COLUMN firm_id SET DEFAULT current_setting('app.firm_id', true)::int;
ALTER TABLE audit_log          ALTER COLUMN firm_id SET DEFAULT current_setting('app.firm_id', true)::int;

-- ============ Row-Level Security pe cele 7 tabele per-firma ============
-- FORCE se aplica si proprietarului tabelei; politica citeste app.firm_id
-- (setat de adaptor la fiecare comutare de firma). WITH CHECK identic cu
-- USING: nu poti nici citi, nici scrie randurile altei firme.

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['clients','client_assignments','reconciliations',
                           'invoices_company','invoices_anaf','differences',
                           'audit_log'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS izolare_firma ON %I', t);
    EXECUTE format(
      'CREATE POLICY izolare_firma ON %I '
      'USING (firm_id = current_setting(''app.firm_id'', true)::int) '
      'WITH CHECK (firm_id = current_setting(''app.firm_id'', true)::int)', t);
  END LOOP;
END $$;

-- ============ drepturi pentru rolul aplicatiei ============
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO etva_app;
-- UPDATE (nu doar USAGE/SELECT) e obligatoriu pentru setval() - fara el,
-- migrarea datelor (portal/migrare_pg.py, pasul final de resetare a
-- secventelor peste MAX(id)) esueaza cu "permission denied for sequence"
-- desi INSERT-urile normale (care doar citesc secventa prin nextval,
-- acoperit de USAGE) merg perfect - descoperit printr-un test real, nu
-- teoretic, vezi tests/test_migrare_pg.py.
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO etva_app;
